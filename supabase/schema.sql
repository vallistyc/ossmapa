create table if not exists public.admin_accounts (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  email text not null unique,
  approved boolean not null default false,
  approved_at timestamptz,
  approved_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.admin_accounts enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false)
    or exists (select 1 from public.admin_accounts where user_id = auth.uid() and approved = true);
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create policy "Admins can read admin accounts"
  on public.admin_accounts for select to authenticated
  using (public.is_admin());
create policy "Users can read own admin account"
  on public.admin_accounts for select to authenticated
  using (user_id = auth.uid());
create policy "Admins can verify admin accounts"
  on public.admin_accounts for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

create table if not exists public.admin_invitations (
  id bigint generated by default as identity primary key,
  email text not null unique check (email = lower(trim(email))),
  invited_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  accepted_at timestamptz
);

alter table public.admin_invitations enable row level security;

create policy "Admins can manage admin invitations"
  on public.admin_invitations for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

create or replace function public.assign_invited_admin_role()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.admin_accounts (user_id, email)
  values (new.id, lower(trim(new.email)))
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_assign_admin on auth.users;
create trigger on_auth_user_created_assign_admin
  after insert on auth.users
  for each row execute function public.assign_invited_admin_role();

