create table if not exists public.admin_invitations (
  id bigint generated by default as identity primary key,
  email text not null unique check (email = lower(trim(email))),
  invited_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  accepted_at timestamptz
);

alter table public.admin_invitations enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false);
$$;

drop policy if exists "Admins can manage admin invitations" on public.admin_invitations;
create policy "Admins can manage admin invitations"
  on public.admin_invitations for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

create or replace function public.assign_invited_admin_role()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if exists (
    select 1 from public.admin_invitations
    where email = lower(trim(new.email))
      and accepted_at is null
  ) then
    new.raw_app_meta_data :=
      coalesce(new.raw_app_meta_data, '{}'::jsonb) || '{"role":"admin"}'::jsonb;
    update public.admin_invitations
    set accepted_at = now()
    where email = lower(trim(new.email)) and accepted_at is null;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_assign_admin on auth.users;
create trigger on_auth_user_created_assign_admin
  before insert on auth.users
  for each row execute function public.assign_invited_admin_role();
