create table if not exists public.admin_accounts (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  email text not null unique,
  approved boolean not null default false,
  approved_at timestamptz,
  approved_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.admin_accounts enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false)
    or exists (
      select 1 from public.admin_accounts
      where user_id = auth.uid() and approved = true
    );
$$;

drop policy if exists "Admins can read admin accounts" on public.admin_accounts;
drop policy if exists "Users can read own admin account" on public.admin_accounts;
drop policy if exists "Admins can verify admin accounts" on public.admin_accounts;
create policy "Admins can read admin accounts"
  on public.admin_accounts for select to authenticated
  using (public.is_admin());
create policy "Users can read own admin account"
  on public.admin_accounts for select to authenticated
  using (user_id = auth.uid());
create policy "Admins can verify admin accounts"
  on public.admin_accounts for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

create or replace function public.create_pending_admin_account()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if exists (
    select 1 from public.admin_invitations
    where email = lower(trim(new.email)) and accepted_at is null
  ) then
    insert into public.admin_accounts (user_id, email)
    values (new.id, lower(trim(new.email)))
    on conflict (user_id) do nothing;
    update public.admin_invitations
    set accepted_at = now()
    where email = lower(trim(new.email)) and accepted_at is null;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_assign_admin on auth.users;
drop trigger if exists on_auth_user_created_pending_admin on auth.users;
create trigger on_auth_user_created_pending_admin
  after insert on auth.users
  for each row execute function public.create_pending_admin_account();
