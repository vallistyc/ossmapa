create table if not exists public.sekbids (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null default 0,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.sekbids enable row level security;

insert into public.sekbids (name, sort_order)
select name, row_number() over (order by name)
from (values
  ('Sekbid 1'), ('Sekbid 2'), ('Sekbid 3'), ('Sekbid 4'), ('Sekbid 5'),
  ('Sekbid 6'), ('Sekbid 7'), ('Sekbid 8'), ('Sekbid 9'), ('Sekbid 10')
) as defaults(name)
on conflict (name) do nothing;

alter table public.programs
  add column if not exists sekbid_id bigint references public.sekbids(id) on delete restrict;

update public.programs
set sekbid_id = sekbids.id
from public.sekbids
where public.programs.sekbid_id is null
  and public.programs.division = sekbids.name;

drop policy if exists "Public can read published sekbids" on public.sekbids;
drop policy if exists "Admins can manage sekbids" on public.sekbids;

create policy "Public can read published sekbids"
  on public.sekbids for select using (published = true);

create policy "Admins can manage sekbids"
  on public.sekbids for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
