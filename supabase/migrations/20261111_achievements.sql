create table if not exists public.achievements (
  id bigint generated by default as identity primary key,
  name text not null,
  class_name text not null,
  title text not null,
  level text not null,
  event_date text not null,
  description text,
  published boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.achievements enable row level security;

drop policy if exists "Public can read published achievements" on public.achievements;
create policy "Public can read published achievements"
  on public.achievements for select using (published = true);

drop policy if exists "Public can submit achievements" on public.achievements;
create policy "Public can submit achievements"
  on public.achievements for insert to anon
  with check (published = false);

drop policy if exists "Admins can manage achievements" on public.achievements;
create policy "Admins can manage achievements"
  on public.achievements for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
